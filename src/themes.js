// Luminancia relativa WCAG de un hex.
function relativeLuminance(hex) {
  const clean = String(hex || '').replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const channels = [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16) / 255);
  const linear = channels.map((v) => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2];
}

// Tinta legible sobre un fondo de acento: la de mayor contraste entre near-black
// y blanco. Se deriva en vez de hardcodear porque el acento del tema 'custom' lo
// elige el usuario y un valor fijo lo dejaría ilegible.
export function pickOnAccent(accent) {
  const l = relativeLuminance(accent);
  const onBlack = (l + 0.05) / (relativeLuminance('#0A0A0A') + 0.05);
  const onWhite = (relativeLuminance('#FFFFFF') + 0.05) / (l + 0.05);
  return onBlack >= onWhite ? '#0A0A0A' : '#FFFFFF';
}

